"""Final Week 3 table: every model x 3 seeds on validation and on TEST (run once, at the end).

The configuration of each model was frozen from validation sweeps (reports/sweeps/) before this
script was run; the test split is read here for the first time. Mean and standard deviation
over the 3 seeds show whether a difference between two models is larger than the noise.

Run:  python -m scentmatch.eval.final_report
Out:  reports/week3_final_results.json, reports/week3_final_tables.md
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from scentmatch.config import load_config
from scentmatch.eval.baselines import most_popular_scores, random_scores
from scentmatch.eval.evaluate import embedding_scores, full_report, notes_only_scores
from scentmatch.eval.harness import EvalData

ROOT = Path(__file__).resolve().parents[3]
MODELS = {
    "LightGCN (no contrastive loss)": "final_lightgcn",
    "NLGCL": "final_nlgcl",
    "NLGCL + note nodes": "final_nlgcl_notes",
    "NLGCL + note nodes + liked low-star reviews": "final_nlgcl_notes_rescued",
}
SEEDS = (1, 2, 3)
SERVED_FAMILY = "final_nlgcl_notes_rescued"
MAIN = ["NDCG@10", "Recall@20", "Coverage@10", "AvgPop@10", "Personalisation@10", "TailShare@10"]
EXTRA = ["NDCG@10[1]", "NDCG@10[2]", "NDCG@10[3-5]", "NDCG@10[6+]", "Recall@20[cold perfumes]",
         "LikeVsDislike", "DislikeInTop20"]


def main() -> None:
    cfg = load_config()
    proc, ck = cfg["paths"]["processed_dir"], cfg["paths"]["checkpoints_dir"]
    fb = pd.read_parquet(proc / "feedback.parquet")
    results: dict = {}
    for split in ("val", "test"):
        data = EvalData.load(proc, with_test=split == "test")
        rows = [full_report("Random", random_scores(data.n_items, 0), data, split, proc, fb),
                full_report("Most-popular", most_popular_scores(data.popularity), data, split, proc, fb),
                full_report("Notes only (content)", notes_only_scores(data, proc, split), data, split, proc, fb)]
        for label, run in MODELS.items():
            for s in SEEDS:
                path = ck / f"{run}_s{s}.pt"
                if path.exists():
                    r = full_report(label, embedding_scores(path, proc), data, split, proc, fb)
                    r["seed"] = s
                    rows.append(r)
                    print(split, label, s, round(r["NDCG@10"], 4), flush=True)
                    if run == SERVED_FAMILY:      # same model, popularity knob beta = 0.5 (chosen on val)
                        r = full_report(label + ", beta = 0.5 (served)", embedding_scores(path, proc, beta=0.5),
                                        data, split, proc, fb)
                        r["seed"] = s
                        rows.append(r)
        results[split] = rows
    (ROOT / "reports" / "week3_final_results.json").write_text(json.dumps(results, indent=1))

    md = ["# Week 3 final tables (generated by scentmatch.eval.final_report)\n"]
    for split in ("val", "test"):
        df = pd.DataFrame(results[split])
        agg = df.groupby("ranker", sort=False)
        for title, cols in (("Accuracy, popularity bias and personalisation", MAIN),
                            ("Segments, cold perfumes and dislikes", EXTRA)):
            md.append(f"\n## {split.upper()} - {title} (mean ± std over seeds for the models)\n")
            md.append("| Ranker | " + " | ".join(cols) + " |")
            md.append("|---|" + "---|" * len(cols))
            for name, g in agg:
                cells = []
                for c in cols:
                    v = g[c].astype(float)
                    cells.append(f"{v.mean():.4f}" + (f" ± {v.std(ddof=1):.4f}" if len(v) > 1 else ""))
                md.append(f"| {name} | " + " | ".join(cells) + " |")
    (ROOT / "reports" / "week3_final_tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
